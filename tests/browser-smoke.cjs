 await page.getByRole('button',{name:'Run optimization',exact:true}).click();
 await page.getByRole('heading',{name:'Review the evidence'}).waitFor({timeout:60000});
 await page.screenshot({path:path.join(out,'optimization.png'),fullPage:true});
 await page.getByRole('button',{name:'Close',exact:true}).click();
 console.log('PASS full-scale optimization -> evidence review');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Overview',exact:true}).click();

 console.log('PASS shortage -> draft requisition');
 await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption('baseline');
 await page.getByRole('button',{name:'Recommendations',exact:false}).first().click();
 await page.getByRole('button',{name:'New optimization',exact:true}).click();
